"""Подготовка текста к отправке в Telegram."""

from __future__ import annotations

import html


def as_pre(text: str) -> str:
    """Обернуть текст в монospace-блок.

    Сводка выровнена пробелами в столбик, а шрифт Telegram по умолчанию
    пропорциональный — в обычном тексте колонки разъехались бы. Внутри <pre>
    содержимое обязательно экранируется: в статье расхода пользователь может
    написать что угодно, включая «<b>».
    """
    return f"<pre>{html.escape(text)}</pre>"
